import json
import unittest
from types import SimpleNamespace as NS
from unittest.mock import AsyncMock, patch

from music_bot.get_song import FetchSettings
from music_bot.youtube_fetch import YouTubeFetcher, FetchError, confident, rank_candidates, recording_artist_aliases


def catalogue_entry(video='abcdefghijk', artist='Artist', title='Song', duration=200):
    return dict(id=video, title=title, artist=artist, track=title, uploader=artist + ' - Topic',
                channel_id='UCcatalogueChannel', album='Studio album', duration=duration,
                description='Provided to YouTube by Distributor\nAuto-generated by YouTube.')


class YouTubeSearchTests(unittest.IsolatedAsyncioTestCase):
    async def asyncSetUp(self):
        mock = patch.object(YouTubeFetcher, 'recording_aliases', new_callable=AsyncMock, return_value=[])
        mock.start()
        self.addCleanup(mock.stop)

    def test_title_alone_cannot_accept_wrong_artist(self):
        for duration in (287, None):
            track = NS(artist='Vigen', title='Sogand', duration=duration)
            self.assertFalse(rank_candidates(track, [dict(id='r0Fi_6FuQ78', title='Sogand',
                uploader='Sam H', duration=175)], 900))

    def test_recording_alias_requires_exact_credit_and_unique_identity(self):
        row = {'title': 'Sogand', 'artist-credit': [{'name': 'Vigen', 'artist': {
            'id': 'artist-one', 'name': 'Vigen Derderian', 'aliases': [{'name': 'Viguen'}]}}]}
        self.assertIn('Viguen', recording_artist_aliases({'recordings': [row]}, 'Vigen', 'Sogand'))
        self.assertFalse(recording_artist_aliases({'recordings': [row]}, 'Vig', 'Sogand'))
        self.assertFalse(recording_artist_aliases({'recordings': [row]}, 'Vigen', 'Other song'))
        other = {'title': 'Sogand', 'artist-credit': [{'name': 'Vigen', 'artist': {'id': 'artist-two'}}]}
        self.assertFalse(recording_artist_aliases({'recordings': [row, other]}, 'Vigen', 'Sogand'))

    async def test_sogand_broadens_before_relaxing_and_finds_verified_topic_alias(self):
        fetcher = YouTubeFetcher(FetchSettings())
        fetcher.recording_aliases.return_value = ['Viguen']
        wrong = dict(id='r0Fi_6FuQ78', title='Sogand', uploader='Sam H', duration=175)
        original = catalogue_entry('fvagwDpwy4s', 'Viguen', 'Sogand', 285)
        fetcher.process = AsyncMock(side_effect=[json.dumps({'entries': [wrong]}).encode(),
            json.dumps({'entries': [original, wrong]}).encode()])
        rows = await fetcher.search(NS(artist='Vigen', title='Sogand', duration=287), '.', AsyncMock(return_value=True))
        self.assertEqual([row['id'] for row in rows], [original['id']])
        self.assertTrue(confident(rows))
        self.assertNotIn('duration_mismatch', rows[0])
        self.assertEqual(fetcher.process.await_args.args[0][-1], 'ytsearch12:Vigen Sogand')

    async def test_full_length_discovery_precedes_clip_duration_recovery(self):
        fetcher = YouTubeFetcher(FetchSettings())
        clip = dict(id='abcdefghijk', title='Artist - Song', uploader='Artist', duration=175)
        original = catalogue_entry('lmnopqrstuv', duration=285)
        fetcher.process = AsyncMock(side_effect=[json.dumps({'entries': [clip]}).encode(),
            json.dumps({'entries': [original]}).encode()])
        rows = await fetcher.search(NS(artist='Artist', title='Song', duration=287), '.', AsyncMock(return_value=True))
        self.assertEqual([row['id'] for row in rows], [original['id']])
        self.assertNotIn('duration_mismatch', rows[0])

    async def test_stored_medley_identity_and_clip_duration_recover_to_choice(self):
        track = NS(artist='navan', title='soltane ghalbha x voilà live montreal concert',
                   display_artist='Navan', display_title='Soltane Ghalbha X Voilà (Live Montreal Concert)', duration=220)
        entry = dict(id='GEaFdwO9YoA',
            title='VOILA x SOLTANE GHALBHA (Live in Montreal) — French x Persian Emotional Cover | Navan',
            channel='Navan', uploader='Navan', duration=272)
        fetcher = YouTubeFetcher(FetchSettings())
        fetcher.process = AsyncMock(return_value=json.dumps({'entries':[entry]}).encode())
        rows = await fetcher.search(track, '.', AsyncMock(return_value=True))
        self.assertFalse(rows)  # Original requests no longer promote unverified performances.
        wrong = dict(entry, title=entry['title'].replace('Montreal','NYC'))
        fetcher.process = AsyncMock(return_value=json.dumps({'entries':[wrong]}).encode())
        self.assertFalse(await fetcher.search(track, '.', AsyncMock(return_value=True)))

    def test_other_medley_versions_still_require_artist_components_and_choice(self):
        track = NS(artist='Navan', title='Soltane Ghalbha X Voilà', duration=None, allow_versions=True)
        entry = dict(id='GEaFdwO9YoA', title='VOILA x SOLTANE GHALBHA (Live in Montreal) — Cover | Navan',
                     channel='Navan', uploader='Navan', duration=272)
        rows = rank_candidates(track,[entry],900)
        self.assertEqual(len(rows),1)
        self.assertFalse(confident(rows))
        for change in [dict(uploader='Other',channel='Other'),dict(title=entry['title']+' Karaoke'),
                       dict(title=entry['title']+' Remix'),dict(title='Other Song (Live Cover)')]:
            self.assertFalse(rank_candidates(track,[{**entry,**change}],900))

    def test_selected_live_medley_can_offer_reversed_cover_but_never_auto_send(self):
        track = NS(artist='Navan', title='Soltane Ghalbha X Voilà (Live Montreal Concert)', duration=272)
        entry = dict(id='GEaFdwO9YoA',
            title='VOILA x SOLTANE GHALBHA (Live in Montreal) — French x Persian Emotional Cover | Navan',
            channel='Navan', uploader='Navan', duration=272)
        rows = rank_candidates(track, [entry], 900)
        self.assertEqual([row['id'] for row in rows], ['GEaFdwO9YoA'])
        self.assertEqual(set(rows[0]['version']), {'live', 'cover'})
        self.assertFalse(rows[0]['exact'])
        self.assertFalse(confident(rows))
        for changes in [dict(channel='Other', uploader='Other'), dict(artist='Other'),
                        dict(title=entry['title'].replace('Montreal', 'NYC')),
                        dict(title=entry['title'].replace('Montreal', '')),
                        dict(title=entry['title'].replace('SOLTANE GHALBHA', 'OTHER SONG')),
                        dict(title=entry['title'].replace('Live in Montreal', 'Montreal')),
                        dict(title=entry['title'] + ' Karaoke'),
                        dict(title=entry['title'] + ' Remix'), dict(duration=950),
                        dict(is_live=True), dict(track='Different Song')]:
            with self.subTest(changes=changes):
                self.assertFalse(rank_candidates(track, [{**entry, **changes}], 900))

    def test_extra_upload_title_text_is_a_choice_not_an_automatic_match(self):
        track = NS(artist='Artist', title='Song Name', duration=200)
        rows = rank_candidates(track, [dict(id='abcdefghijk', title='Artist - Song Name extra upload credits and packaging',
            uploader='Artist', duration=200)], 900)
        self.assertEqual(len(rows), 1)
        self.assertTrue(rows[0]['title_mismatch'])
        self.assertFalse(confident(rows))
        for title, uploader in [('Other Song Name packaging credits', 'Unknown'),
                                ('Artist - Song Name (Cover)', 'Artist'),
                                ('Artist - Song Name (Karaoke)', 'Artist'),
                                ('Artist - Song Names packaging', 'Artist')]:
            self.assertFalse(rank_candidates(track, [dict(id='abcdefghijk', title=title, uploader=uploader, duration=200)], 900))

    def test_other_versions_offer_diversity_without_covers_or_wrong_artists(self):
        from music_bot.youtube_fetch import base_title
        self.assertEqual(base_title('Song (Live)'), 'Song')
        self.assertEqual(base_title('Live Forever'), 'Live Forever')
        track = NS(artist='Artist', title='Song', duration=None, allow_versions=True)
        entries = [dict(id='abcdefghij' + str(i), title='Artist - Song' + suffix,
                        artist=artist, duration=200) for i, (suffix, artist) in enumerate([
            ('', 'Artist'), (' (Live)', 'Artist'), (' (Acoustic)', 'Artist'),
            (' (Cover)', 'Artist'), ('', 'Other')])]
        rows = rank_candidates(track, entries, 900)
        self.assertEqual({tuple(r['version']) for r in rows}, {(), ('live',), ('acoustic',)})

    async def test_search_keeps_catalogue_punctuation(self):
        fetcher = YouTubeFetcher(FetchSettings())
        fetcher.process = AsyncMock(return_value=b'{"entries": []}')
        await fetcher.search(NS(artist='artist', title='untitled 02 l 06 23 2014', duration=None,
            display_artist='Artist', display_title='untitled 02 l 06.23.2014.'), '.', AsyncMock())
        query = fetcher.process.await_args_list[0].args[0][-1]
        self.assertEqual(query, 'ytsearch8:Artist untitled 02 l 06.23.2014. official audio')

    async def test_clip_duration_does_not_substitute_for_original(self):
        fetcher = YouTubeFetcher(FetchSettings())
        rows = [dict(id='abcdefghijk', title='Kendrick Lamar - DNA.', uploader='Kendrick Lamar', duration=187),
                dict(id='bcdefghijkl', title='Kendrick Lamar - DNA. cover', uploader='Other', duration=187)]
        fetcher.process = AsyncMock(return_value=json.dumps({'entries': rows}).encode())
        result = await fetcher.search(NS(artist='Kendrick Lamar', title='DNA.', duration=116), '.', AsyncMock())
        self.assertFalse(result)
        arguments = fetcher.process.call_args_list[0].args[0]
        self.assertIn('--flat-playlist', arguments)
        self.assertIn('--no-cookies-from-browser', arguments)

    async def test_matching_duration_has_no_mismatch_warning(self):
        fetcher = YouTubeFetcher(FetchSettings())
        fetcher.process = AsyncMock(return_value=json.dumps({'entries': [catalogue_entry(duration=187)]}).encode())
        result = await fetcher.search(NS(artist='Artist', title='Song', duration=187), '.', AsyncMock())
        self.assertNotIn('duration_mismatch', result[0])
        self.assertTrue(confident(result))

    async def test_bad_metadata_fails_with_fixed_error(self):
        fetcher = YouTubeFetcher(FetchSettings())
        fetcher.process = AsyncMock(return_value=b'private provider error')
        with self.assertRaisesRegex(FetchError, '^Source metadata unavailable.$'):
            await fetcher.search(NS(artist='Artist', title='Song', duration=187), '.', AsyncMock())

    def test_official_audio_beats_lyrics_and_equivalent_duplicates_need_no_choice(self):
        track = NS(artist='Artist', title='Song', duration=200)
        rows = [dict(id='abcdefghijk', title='Artist - Song (Official Audio)', uploader='Artist', duration=200),
                dict(id='bcdefghijkl', title='Song', uploader='Artist - Topic', duration=201),
                dict(id='cdefghijklm', title='Artist - Song (Lyrics)', uploader='Someone', duration=200)]
        ranked = rank_candidates(track, rows, 900)
        self.assertEqual(ranked[0]['id'], 'abcdefghijk')
        self.assertTrue(confident(ranked))

    def test_official_recording_is_not_ambiguous_with_matching_fan_upload(self):
        track = NS(artist='Kendrick Lamar', title='DNA.', duration=185)
        rows = [dict(id='abcdefghijk', title='DNA.', track='DNA.', artist='Kendrick Lamar', uploader='Kendrick Lamar', duration=186),
                dict(id='bcdefghijkl', title='DNA - Kendrick Lamar (AUDIO)', uploader='Fan', duration=187)]
        self.assertTrue(confident(rank_candidates(track, rows, 900)))

    def test_different_lengths_still_require_recording_choice(self):
        track = NS(artist='Artist', title='Song', duration=200)
        rows = [dict(id='abcdefghijk', title='Song', track='Song', artist='Artist', duration=200),
                dict(id='bcdefghijkl', title='Song', track='Song', artist='Artist', duration=205)]
        self.assertFalse(confident(rank_candidates(track, rows, 900)))

    def test_versions_and_wrong_explicit_artist_cannot_be_auto_selected(self):
        track = NS(artist='Artist', title='Song', duration=200)
        for label in ['Live', 'Remastered', 'Cover', 'Karaoke', 'Slowed + Reverb', 'Remix', 'Extended', '432hz']:
            self.assertFalse(rank_candidates(track, [dict(id='abcdefghijk', track='Song', artist='Artist',
                title='Artist - Song (' + label + ')', duration=200)], 900))
        self.assertFalse(rank_candidates(track, [dict(id='abcdefghijk', track='Song', artist='Other Artist',
            title='Song', duration=200)], 900))
        ranked = rank_candidates(track, [dict(id='abcdefghijk', title='Artist - Song', uploader='Fan', duration=200)], 900)
        self.assertFalse(confident(ranked))

    async def test_catalogue_details_resolve_flat_search_uncertainty(self):
        fetcher = YouTubeFetcher(FetchSettings())
        flat = dict(id='abcdefghijk', title='Song', uploader='Artist - Topic', duration=200)
        detail = catalogue_entry()
        listing = json.dumps({'entries': [flat]}).encode()
        fetcher.process = AsyncMock(side_effect=[listing, listing, json.dumps(detail).encode()])
        result = await fetcher.search(NS(artist='Artist', title='Song', duration=200), '.', AsyncMock(return_value=True))
        self.assertTrue(confident(result))
        self.assertEqual(fetcher.process.await_count, 3)

